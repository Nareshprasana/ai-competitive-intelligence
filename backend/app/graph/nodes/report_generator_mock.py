"""report_generator_mock node: deterministic mock final report assembly."""

from app.graph.nodes.base import run_node
from app.graph.state import ResearchState


async def _report_generator(state: ResearchState) -> dict:
    report = {
        "report_id": f"rpt-{state.research_id}",
        "title": f"Competitive Intelligence Report: {state.company_name}",
        "company": state.company_name,
        "industry": state.industry,
        "research_question": state.research_question,
        "sections": {
            "executive_summary": (
                f"Mock executive summary for {state.company_name} in {state.industry}. "
                "This report was generated by deterministic mock agents in Phase 1."
            ),
            "company_profile": state.company_profile,
            "competitors": state.competitors,
            "market_intelligence": state.market_intelligence or {
                "note": "No market intelligence produced by mock agents.",
            },
            "strategic_analysis": state.strategic_analysis,
            "evidence": state.evidence,
            "validation_results": state.validation_results,
        },
        "generated_by": "report_generator_mock",
        "mock": True,
    }
    return {
        "final_report": report,
        "_metadata_details": {"report_id": report["report_id"]},
    }


async def report_generator_mock(state: ResearchState) -> dict:
    """Assemble the deterministic mock final report (not real research output)."""
    if not state.company_name:
        raise ValueError("company_name is required to generate a report.")
    return await run_node(
        node_name="report_generator_mock",
        state=state,
        node_fn=_report_generator,
        mock=True,
    )
